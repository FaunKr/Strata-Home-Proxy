#!/usr/bin/env bash
# Tests scripts/check-session-links.sh.
set -euo pipefail
cd "$(dirname "$0")/.."
check=scripts/check-session-links.sh

failures=0
fail() {
  echo "check-session-links: $1" >&2
  failures=$((failures + 1))
}
printf 'Fix the timer\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n' \
  | "$check" 2>/dev/null || fail "plain attribution fails"
printf 'Fix\n\nClaude-Session: https://claude.ai/code/session_011abc\n' \
  | "$check" 2>/dev/null && fail "a Claude-Session line passes"
printf '_Generated by [Claude Code](https://claude.ai/code/session_011abc)_\n' \
  | "$check" 2>/dev/null && fail "a session link passes"
printf '[thread](https://claude.ai/code/project/chan_01?thread=cmsg_01)\n' \
  | "$check" 2>/dev/null && fail "a thread link passes"
if ((failures)); then
  exit 1
fi
echo "check-session-links: ok"
